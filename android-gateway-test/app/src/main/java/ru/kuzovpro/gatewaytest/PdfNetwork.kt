package ru.kuzovpro.gatewaytest

import java.net.HttpURLConnection
import java.net.URL
import java.net.URLDecoder
import java.security.MessageDigest
import java.util.Base64
import java.util.UUID

class UploadTicket(val url: String, headers: Map<String, String>, val expiresSeconds: Int) {
    val headers: Map<String, String> = headers.toMap()
    override fun toString() = "UploadTicket(redacted)"
}

data class PutResult(val status: Int, val md5Confirmed: Boolean)
data class DocumentCheck(val status: Int, val matches: Boolean) {
    val unavailable: Boolean get() = status == 403 || status == 404
}

interface PdfNetwork {
    fun put(ticket: UploadTicket, id: String, pdf: PdfPayload): PutResult
    fun check(id: String, pdf: PdfPayload?): DocumentCheck
}

fun connectionFailure(error: Exception): String = when (error) {
    is java.net.UnknownHostException -> "Не удалось найти адрес сервера (DNS)."
    is java.net.SocketTimeoutException -> "Истекло время ожидания ответа."
    is javax.net.ssl.SSLException -> "Ошибка защищённого TLS-соединения; проверьте дату телефона и сеть."
    is java.net.ConnectException -> "Соединение с сервером не установлено."
    is java.io.IOException -> "Сетевое соединение прервано."
    is java.security.GeneralSecurityException -> "Не удалось использовать тестовый ключ."
    else -> "Не удалось выполнить запрос."
}

class HttpsPdfNetwork(private val open: (URL) -> HttpURLConnection = { it.openConnection() as HttpURLConnection }) : PdfNetwork {
    override fun put(ticket: UploadTicket, id: String, pdf: PdfPayload): PutResult {
        val url = validateTicket(ticket, id, pdf)
        val c = open(url)
        try {
            configure(c)
            c.requestMethod = "PUT"
            c.doOutput = true
            // Content-Length is generated by fixed-length streaming, with exactly the signed value.
            ticket.headers.forEach { (name, value) -> if (!name.equals("Content-Length", true)) c.setRequestProperty(name, value) }
            c.setFixedLengthStreamingMode(pdf.size)
            c.outputStream.use { it.write(pdf.bytes()) }
            val status = c.responseCode
            val md5Hex = Protocol.hex(Base64.getDecoder().decode(pdf.md5))
            val etag = c.getHeaderField("ETag")?.trim()?.removeSurrounding("\"")
            // Small, single-part, non-encrypted test PUT: an S3 ETag should equal MD5.
            return PutResult(status, status in 200..299 && etag == md5Hex)
        } finally { c.disconnect() }
    }

    override fun check(id: String, pdf: PdfPayload?): DocumentCheck {
        val c = open(URL(Protocol.publicUrl(id) + "?kpro_check=" + UUID.randomUUID().toString()))
        try {
            configure(c)
            c.requestMethod = "GET"
            c.setRequestProperty("Cache-Control", "no-cache, no-store, max-age=0")
            c.setRequestProperty("Pragma", "no-cache")
            c.setRequestProperty("Accept-Encoding", "identity")
            val status = c.responseCode
            if (status != 200 || pdf == null) return DocumentCheck(status, false)
            if (c.contentType?.substringBefore(';')?.trim()?.lowercase() != "application/pdf") return DocumentCheck(status, false)
            val digest = MessageDigest.getInstance("SHA-256")
            var count = 0
            c.inputStream.use { stream ->
                val buffer = ByteArray(4096)
                while (count <= pdf.size) {
                    val n = stream.read(buffer, 0, minOf(buffer.size, pdf.size + 1 - count))
                    if (n < 0) break
                    if (n == 0) break
                    digest.update(buffer, 0, n)
                    count += n
                }
            }
            return DocumentCheck(status, count == pdf.size && Protocol.hex(digest.digest()) == pdf.sha256)
        } finally { c.disconnect() }
    }

    private fun configure(c: HttpURLConnection) {
        c.instanceFollowRedirects = false
        c.useCaches = false
        c.connectTimeout = 15_000
        c.readTimeout = 60_000
    }

    companion object {
        fun validateTicket(ticket: UploadTicket, id: String, pdf: PdfPayload): URL {
            require(Protocol.idPattern.matches(id))
            val url = URL(ticket.url)
            require(url.protocol == "https" && url.host == "storage.yandexcloud.net" && url.port == -1 &&
                url.userInfo == null && url.ref == null)
            require(Regex("/[a-z0-9][a-z0-9.-]{1,61}[a-z0-9]/staging/$id\\.pdf").matches(url.path))
            val headers = ticket.headers.entries.associate { it.key.lowercase() to it.value }
            require(headers.size == ticket.headers.size && headers.keys == setOf("content-type", "content-length", "content-md5", "if-none-match"))
            require(headers["content-type"] == "application/pdf" && headers["content-length"] == pdf.size.toString() &&
                headers["content-md5"] == pdf.md5 && headers["if-none-match"] == "*")
            val query = url.query.orEmpty().split('&').map { part ->
                val pieces = part.split('=', limit = 2)
                URLDecoder.decode(pieces[0], "UTF-8").lowercase() to URLDecoder.decode(pieces.getOrElse(1) { "" }, "UTF-8")
            }
            require(query.map { it.first }.distinct().size == query.size)
            val params = query.toMap()
            val signedHeaders = params["x-amz-signedheaders"].orEmpty().lowercase().split(';').toSet()
            require(signedHeaders.containsAll(headers.keys + "host"))
            require(params["x-amz-algorithm"] == "AWS4-HMAC-SHA256" &&
                Regex("[a-fA-F0-9]{64}").matches(params["x-amz-signature"].orEmpty()))
            require(ticket.expiresSeconds in 1..300 && params["x-amz-expires"]?.toIntOrNull() in 1..300)
            return url
        }
    }
}
